/**
 * 数据类型枚举
 */
export enum DataType {
    /** 字符串 */
    STRING = 'STRING',
    /** 数字 */
    NUMBER = 'NUMBER',
    /** 布尔值 */
    BOOLEAN = 'BOOLEAN',
    /** 日期 */
    DATE = 'DATE',
    /** 日期时间 */
    DATETIME = 'DATETIME',
    /** 数组 */
    ARRAY = 'ARRAY',
    /** 对象 */
    OBJECT = 'OBJECT'
}
